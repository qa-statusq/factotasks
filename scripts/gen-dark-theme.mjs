// Generates src/app/theme-dark.css (the dark palette) from the stock Tailwind colours.
// Run: node scripts/gen-dark-theme.mjs
import { readFileSync, writeFileSync } from "node:fs";
const theme = readFileSync(new URL("../node_modules/tailwindcss/theme.css", import.meta.url), "utf8");
const val = (hue, s) => theme.match(new RegExp(`--color-${hue}-${s}:\s*([^;]+);`))[1].trim();
const NL = String.fromCharCode(10), BS = String.fromCharCode(92);
const HUES = ["red", "amber", "emerald", "sky", "blue", "violet", "indigo", "orange", "teal", "rose", "slate", "green", "yellow", "purple", "pink", "cyan", "lime"];
const BASE = "#1d1d1c"; // the dark surface the tints sit on
const tokens = `
  color-scheme: dark;
  --color-canvas: #121211;
  --color-surface: #1d1d1c;
  --color-line: #31312e;
  --color-ink: #ecebe7;
  --color-ink-muted: #aeada6;
  --color-ink-subtle: #807f78;
  --color-on-ink: #141413;
  --color-ink-hover: #d5d4cf;
  --color-toast: #2b2b29;
  --color-chrome: rgba(18, 18, 17, 0.96);
  --color-select: rgba(236, 235, 231, 0.18);
  --color-scroll: #45453f;
  --color-scroll-hover: #5d5d56;
  --color-brand-50: #252523;
  --color-brand-100: #2c2c2a;
  --color-brand-200: #3a3a37;
  --color-brand-300: #4f4f4b;
  --color-brand-400: #807f78;
  --color-brand-500: #aeada6;
  --color-brand-600: #ecebe7;
  --color-brand-700: #f5f5f2;
  --color-brand-800: #fafaf8;
  --color-brand-900: #ecebe7;
  --shadow-xs: 0 1px 2px 0 rgba(0, 0, 0, 0.4);
  --shadow-card: 0 1px 2px 0 rgba(0, 0, 0, 0.35);
  --shadow-pop: 0 28px 64px -20px rgba(0, 0, 0, 0.7), 0 10px 24px -10px rgba(0, 0, 0, 0.5), 0 0 0 1px rgba(255, 255, 255, 0.06);
` + HUES.map((h) => {
  const c500 = val(h, 500);
  return [
    `  --color-${h}-50: color-mix(in oklab, ${c500} 14%, ${BASE});`,
    `  --color-${h}-100: color-mix(in oklab, ${c500} 22%, ${BASE});`,
    `  --color-${h}-200: color-mix(in oklab, ${c500} 34%, ${BASE});`,
    `  --color-${h}-700: ${val(h, 300)};`,
    `  --color-${h}-800: ${val(h, 200)};`,
    `  --color-${h}-900: ${val(h, 100)};`,
  ].join("\n");
}).join("\n");
// Text that is "600" (danger links, delete hovers) is lifted to 400 so it reads on a dark surface;
// 600 itself stays for solid fills (checkboxes, buttons) that carry white text.
const text600 = (sel) => HUES.map((h) => `  ${sel} .text-${h}-600, ${sel} .hover${BS}:text-${h}-600:hover { color: ${val(h, 400)}; }`).join(NL);
// Paper-like islands (the minutes document, slides) stay light inside a dark panel.
const lightTokens = `
  color-scheme: light;
  --color-canvas: #f7f7f5;
  --color-surface: #ffffff;
  --color-line: #e7e6e2;
  --color-ink: #1c1c1a;
  --color-ink-muted: #5c5c57;
  --color-ink-subtle: #8c8c85;
  --color-on-ink: #ffffff;
  --color-ink-hover: #2a2a27;
  --color-brand-50: #f1f1ee;
  --color-brand-100: #e6e6e1;
  --color-brand-200: #d3d3cc;
  --color-brand-300: #b4b4ab;
  --color-brand-400: #8c8c85;
  --color-brand-500: #5c5c57;
  --color-brand-600: #1c1c1a;
  --color-brand-700: #111110;
  --color-brand-800: #0b0b0a;
  --color-brand-900: #141413;
` + HUES.map((h) => [50, 100, 200, 700, 800, 900].map((n) => `  --color-${h}-${n}: ${val(h, n)};`).join(NL)).join(NL);
const text600Reset = (sel) => HUES.map((h) => `  ${sel} .theme-light .text-${h}-600, ${sel} .theme-light .hover${BS}:text-${h}-600:hover { color: ${val(h, 600)}; }`).join(NL);
const css = `/* GENERATED by scripts/gen-dark-theme.mjs — edit that, then run: node scripts/gen-dark-theme.mjs — the dark theme.
   Chosen per person (Profile → Appearance), stored on their account and in the
   ft_theme cookie so the server paints the right theme on the first frame.
   html[data-theme] is "light" | "dark" | "system"; "system" follows the OS.
   Screen only: printing always uses the light, paper-friendly palette.

   How the whole panel turns dark without a dark: class on every element:
   - the semantic tokens (canvas, surface, line, ink…) switch values;
   - the stock tints (bg-*-50/100/200 for chips, banners and rings) become
     low-light tints of the same hue, and *-700/800/900 text becomes its light
     counterpart, so "amber text on an amber wash" stays readable;
   - 400–600 (solid fills that carry white text) keep their colour. */
@media screen {
  :root[data-theme="dark"] {${tokens}
  }
${text600(':root[data-theme="dark"]')}
  :root[data-theme="dark"] .theme-light {${lightTokens}
  }
${text600Reset(':root[data-theme="dark"]')}
}
@media screen and (prefers-color-scheme: dark) {
  :root[data-theme="system"] {${tokens}
  }
${text600(':root[data-theme="system"]')}
  :root[data-theme="system"] .theme-light {${lightTokens}
  }
${text600Reset(':root[data-theme="system"]')}
}
`;
writeFileSync(new URL("../src/app/theme-dark.css", import.meta.url), css);
console.log("wrote", css.length, "bytes");
