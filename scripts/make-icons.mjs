// Generates every raster brand asset from the ONE source of truth — the inline
// SVG in src/components/ui/logo.tsx (mirrored below):
//   public/brand/icon.svg          vector mark
//   public/brand/icon-192.png      PWA / Android home screen
//   public/brand/icon-512.png      PWA splash
//   public/brand/maskable-512.png  PWA maskable (20% safe-zone padding)
//   public/apple-touch-icon.png    iOS home screen (180)
//   src/app/icon.png               browser favicon (Next app-dir convention, 192, rounded)
//   public/favicon.ico            classic favicon (16/32/48, PNG-in-ICO)
//   public/favicon-32.png         explicit <link rel=icon> fallback
//   public/offline.html            <- grayscale data-URI favicon patched in place
// Re-run after changing the mark:  npm run favicon
import sharp from "sharp";
import { mkdir, readFile, writeFile } from "node:fs/promises";

const BRAND = "#059669";
const mark = (bg = BRAND, fg = "#fff", pad = 0, tick = "#fff") => {
  // pad = fraction of the canvas reserved around the mark (maskable icons).
  const s = 32 / (1 - 2 * pad);
  const off = (s - 32) / 2;
  return Buffer.from(
    `<svg xmlns="http://www.w3.org/2000/svg" width="${s}" height="${s}" viewBox="0 0 ${s} ${s}">` +
      (pad ? `<rect width="${s}" height="${s}" fill="${bg}"/>` : `<rect width="32" height="32" rx="8" fill="${bg}"/>`) +
      `<g transform="translate(${off} ${off})">` +
      `<path d="M9 6.5h14a3 3 0 0 1 0 6h-8v2.5h6.5a2.75 2.75 0 0 1 0 5.5H15v3a3 3 0 0 1-6 0V6.5z" fill="${fg}"/>` +
      `<path d="M18 24.4l2.6 2.6 5.6-6" fill="none" stroke="${tick}" stroke-width="3.6" stroke-linecap="round" stroke-linejoin="round"/>` +
      `</g></svg>`
  );
};

await mkdir("public/brand", { recursive: true });

const png = (svg, size, out) =>
  sharp(svg, { density: 384 }).resize(size, size).png({ compressionLevel: 9 }).toFile(out);

await png(mark(), 192, "public/brand/icon-192.png");
await png(mark(), 512, "public/brand/icon-512.png");
await png(mark(BRAND, "#fff", 0.2), 512, "public/brand/maskable-512.png");
await png(mark(), 180, "public/apple-touch-icon.png");
await png(mark(), 192, "src/app/icon.png");

// /favicon.ico — browsers still ask for it by name. ICO may carry PNG-encoded
// images (every current browser reads them), so pack 16/32/48 px PNGs.
const icoSizes = [16, 32, 48];
const pngs = await Promise.all(icoSizes.map((sz) => sharp(mark(), { density: 384 }).resize(sz, sz).png({ compressionLevel: 9 }).toBuffer()));
const header = Buffer.alloc(6);
header.writeUInt16LE(0, 0); // reserved
header.writeUInt16LE(1, 2); // type: icon
header.writeUInt16LE(pngs.length, 4);
const dir = Buffer.alloc(16 * pngs.length);
let offset = 6 + dir.length;
pngs.forEach((buf, i) => {
  const sz = icoSizes[i];
  dir.writeUInt8(sz >= 256 ? 0 : sz, i * 16 + 0);
  dir.writeUInt8(sz >= 256 ? 0 : sz, i * 16 + 1);
  dir.writeUInt8(0, i * 16 + 2); // palette
  dir.writeUInt8(0, i * 16 + 3); // reserved
  dir.writeUInt16LE(1, i * 16 + 4); // planes
  dir.writeUInt16LE(32, i * 16 + 6); // bpp
  dir.writeUInt32LE(buf.length, i * 16 + 8);
  dir.writeUInt32LE(offset, i * 16 + 12);
  offset += buf.length;
});
await writeFile("public/favicon.ico", Buffer.concat([header, dir, ...pngs]));
await png(mark(), 32, "public/favicon-32.png");

// Offline page: a GRAYSCALE mark so the tab icon reads "disconnected" even
// before the page paints. Embedded as a data: URI — nothing can be fetched offline.
const gray = await sharp(mark("#9ca3af", "#fff", 0, "#e5e7eb"), { density: 384 }).resize(64, 64).png({ compressionLevel: 9 }).toBuffer();
const dataUri = `data:image/png;base64,${gray.toString("base64")}`;
const offline = await readFile("public/offline.html", "utf8");
const patched = offline.replace(/data:image\/png;base64,[A-Za-z0-9+/=]+/g, dataUri);
await writeFile("public/offline.html", patched);
// The in-app offline favicon swap (NetworkStrip) needs the same bytes as a
// string constant — a /path icon can't be fetched while disconnected.
await writeFile(
  "src/lib/offline-favicon.ts",
  `// GENERATED by scripts/make-icons.mjs — do not edit. Grayscale brand mark as a\n// data: URI for the offline favicon swap (nothing can be fetched offline).\nexport const OFFLINE_FAVICON = ${JSON.stringify(dataUri)};\n`
);

console.log("Brand assets written (svg, 192/512/maskable/apple/favicon) and offline.html favicon patched.");
